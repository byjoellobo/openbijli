/**
 * Validates data/ and generates:
 *   packages/data/src/generated/catalog.ts   typed, bundled catalog
 *   data/schema/tariff-book.schema.json       JSON Schema for editors ("$schema" in each file)
 *
 * Usage: tsx scripts/build-data.ts [--check]
 *   --check  validate only; exit non-zero if the committed JSON Schema is stale.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { z } from 'zod';
import { NationalFileSchema, SolarResourceFileSchema, TariffBookSchema } from '../packages/data/src/schema.js';
import { DATA_DIR, ROOT, loadData } from './lib/data-files.js';

const checkOnly = process.argv.includes('--check');
const log = (line: string): void => {
  process.stdout.write(`${line}\n`);
};

const JSON_SCHEMAS: ReadonlyArray<{ file: string; title: string; schema: z.ZodType }> = [
  { file: 'tariff-book.schema.json', title: 'Open Tariff India tariff book', schema: TariffBookSchema },
  { file: 'solar-resource.schema.json', title: 'Open Tariff India solar resource file', schema: SolarResourceFileSchema },
  { file: 'national.schema.json', title: 'Open Tariff India national parameters', schema: NationalFileSchema },
];

function jsonSchemaText(schema: z.ZodType, title: string): string {
  const json = z.toJSONSchema(schema, { io: 'input', target: 'draft-2020-12' });
  return `${JSON.stringify({ ...json, title }, null, 2)}\n`;
}

async function main(): Promise<void> {
  const { catalog, books, errors, warnings } = await loadData();
  for (const warning of warnings) log(`warn  ${warning}`);
  if (errors.length > 0 || !catalog) {
    for (const error of errors) process.stderr.write(`error ${error}\n`);
    process.stderr.write(`\n${errors.length} error(s) in data/. Nothing was generated.\n`);
    process.exit(1);
  }

  const schemaDir = path.join(DATA_DIR, 'schema');
  if (checkOnly) {
    for (const { file, title, schema } of JSON_SCHEMAS) {
      const committed = await readFile(path.join(schemaDir, file), 'utf8').catch(() => '');
      if (committed !== jsonSchemaText(schema, title)) {
        process.stderr.write(`data/schema/${file} is stale. Run npm run data:build and commit it.\n`);
        process.exit(1);
      }
    }
    log(`ok    ${books.length} tariff book(s) valid`);
    return;
  }

  await mkdir(schemaDir, { recursive: true });
  for (const { file, title, schema } of JSON_SCHEMAS) {
    await writeFile(path.join(schemaDir, file), jsonSchemaText(schema, title));
  }

  const outDir = path.join(ROOT, 'packages', 'data', 'src', 'generated');
  await mkdir(outDir, { recursive: true });
  const source = [
    '// AUTO-GENERATED by scripts/build-data.ts from data/. Do not edit by hand.',
    "import type { Catalog } from '../types.js';",
    '',
    `export const catalog: Catalog = ${JSON.stringify(catalog, null, 2)};`,
    '',
  ].join('\n');
  await writeFile(path.join(outDir, 'catalog.ts'), source);
  log(`ok    ${books.length} tariff book(s), ${catalog.solar.locations.length} solar locations -> packages/data/src/generated/catalog.ts`);
}

main().catch((error: unknown) => {
  process.stderr.write(`${error instanceof Error ? error.stack ?? error.message : String(error)}\n`);
  process.exit(1);
});

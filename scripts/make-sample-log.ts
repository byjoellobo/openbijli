/**
 * Regenerates the Meter Sakshi demo files in hardware/meter-sakshi/samples/:
 * a 3-day log with an outage during a prepaid recharge, a no-load test that shows
 * creep, and a reference-load test, plus a matching case file.
 *
 * Usage: tsx scripts/make-sample-log.ts
 */
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { simulateLog } from '../packages/evidence/src/simulate.js';
import { ROOT } from './lib/data-files.js';

const OUT = path.join(ROOT, 'hardware', 'meter-sakshi', 'samples');

async function main(): Promise<void> {
  const { text, log } = await simulateLog({
    deviceId: 'MS-DEMO01',
    impPerKwh: 3200,
    startIso: '2026-10-01T00:00:00+05:30',
    days: 3,
    dailyKwh: 9,
    seed: 7,
    digests: true,
    outages: [{ startIso: '2026-10-02T09:00:00+05:30', minutes: 300 }],
    creepTest: { startIso: '2026-10-03T01:00:00+05:30', minutes: 20, leakWatts: 45 },
    referenceTest: { startIso: '2026-10-03T02:00:00+05:30', minutes: 30, watts: 2000, meterErrorPct: 0.5 },
  });
  const observed = log.records.reduce((sum, r) => sum + r.pulses, 0) / 3200;
  const caseFile = {
    consumer: { name: 'Demo household', accountNumber: 'DEMO-0001' },
    utilityId: 'mescom',
    sanctionedLoadKw: 3,
    phase: 'single',
    meter: { type: 'prepaid', make: 'Example smart meter', serial: 'DEMO123456' },
    bills: [
      {
        id: 'Oct-1-3',
        periodStart: '2026-10-01T00:00:00+05:30',
        periodEnd: '2026-10-04T00:00:00+05:30',
        billedUnits: Math.round(observed * 1.3),
        billedAmount: 420,
      },
    ],
    prepaidLedger: [
      { timestamp: '2026-10-02T09:30:00+05:30', type: 'recharge', amount: 500, note: 'UPI recharge after low balance cut-off' },
      { timestamp: '2026-10-01T23:55:00+05:30', type: 'deduction', amount: 95 },
      { timestamp: '2026-10-02T23:55:00+05:30', type: 'deduction', amount: 160 },
      { timestamp: '2026-10-03T23:55:00+05:30', type: 'deduction', amount: 98 },
    ],
    creepTests: [{ start: '2026-10-03T01:00:00+05:30', end: '2026-10-03T01:20:00+05:30' }],
    referenceTests: [
      { start: '2026-10-03T02:00:00+05:30', end: '2026-10-03T02:30:00+05:30', referenceWatts: 2000, instrumentAccuracyPct: 2, instrument: 'Plug-in energy monitor' },
    ],
    reconnectionStandardHours: 2,
    notes: 'Demo data generated by scripts/make-sample-log.ts. Not a real household.',
  };
  await mkdir(OUT, { recursive: true });
  await writeFile(path.join(OUT, 'sample-log.csv'), text);
  await writeFile(path.join(OUT, 'sample-case.json'), `${JSON.stringify(caseFile, null, 2)}\n`);
  process.stdout.write(`ok    wrote ${log.records.length} records (${observed.toFixed(2)} kWh) and a case file to ${path.relative(ROOT, OUT)}\n`);
}

main().catch((error: unknown) => {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  process.exit(1);
});
